def test_smauto_basic_transformation(clean_output):
    """Test basic transformation with Sensor (BME680) and MQTT Broker."""
    demol_str = """
    DEVICE TestDevice WITH
        description="Test Device",
        author="Tester",
        os=riotos;
    
    USE RaspberryPi_5_8GB;
    USE BME680 [EnvSensor];
    
    NETWORK [WiFi] WITH ssid="ssid", password="pass";
    
    BROKER [MQTT] MyBroker WITH
        host="localhost",
        port=1883,
        auth.username="user",
        auth.password="pass";
        
    CONNECT EnvSensor WITH
        POWER gnd -- GND_1, vcc -- power_5v_a
        DATA i2c [slave_address=0x77] sda sda -- GPIO2, scl scl -- GPIO3;
    """

    mm = get_device_mm()
    model = mm.model_from_str(demol_str)

    # Run transformation
    demol2smauto(model, output_dir=OUTPUT_DIR)

    # Verify file exists
    expected_file = os.path.join(OUTPUT_DIR, "TestDeviceSmAutoModel.auto")
    assert os.path.exists(expected_file)

    # Verify content
    with open(expected_file, "r") as f:
        content = f.read()

    assert "Broker<MQTT> MyBroker" in content
    assert 'host: "localhost"' in content
    assert "port: 1883" in content
    assert 'username: "user"' in content
    assert 'password: "pass"' in content

    assert "Entity EnvSensor" in content
    assert "type: sensor" in content.lower()
    # Topic is auto-generated by enrich_model: device_name.type.msg_type.instance_name
    assert 'topic: "testdevice.sensor.env.envsensor"' in content
    assert "broker: MyBroker" in content

    # Check attributes for Env message type
    assert "- temperature: float" in content
    assert "- pressure: float" in content
    assert "- humidity: float" in content
    assert "- gas_resistance: float" in content

    # BME680 doesn't have frequency attribute, so freq should be default 1
    assert "freq: 1" in content



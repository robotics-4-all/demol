def test_smauto_broker_variants(clean_output):
    """Test transformation with different Broker types (AMQP, Redis)."""
    # AMQP
    demol_str_amqp = """
    DEVICE AMQPTest WITH description="D", author="A", os=riotos;
    USE RaspberryPi_5_8GB;
    USE LedGeneric [Led];
    
    NETWORK [WiFi] WITH ssid="ssid", password="pass";
    
    BROKER [AMQP] AmqpBroker WITH
        host="localhost", port=5672,
        auth.username="u", auth.password="p",
        vhost="/", topicExchange="amq.topic";
    
    CONNECT Led WITH POWER gnd--GND_1, vcc--power_3v3_a DATA gpio[mode="output"] vin--GPIO18;
    """
    mm = get_device_mm()
    model = mm.model_from_str(demol_str_amqp)
    demol2smauto(model, output_dir=OUTPUT_DIR)

    with open(os.path.join(OUTPUT_DIR, "AMQPTestSmAutoModel.auto"), "r") as f:
        content = f.read()
    assert "Broker<AMQP> AmqpBroker" in content
    assert 'vhost: "/"' in content
    assert 'topicExchange: "amq.topic"' in content

    # Redis
    demol_str_redis = """
    DEVICE RedisTest WITH description="D", author="A", os=riotos;
    USE RaspberryPi_5_8GB;
    USE LedGeneric [Led];
    
    NETWORK [WiFi] WITH ssid="ssid", password="pass";
    
    BROKER [Redis] RedisBroker WITH
        host="localhost", port=6379,
        auth.username="u", auth.password="p",
        db=0;
    
    CONNECT Led WITH POWER gnd--GND_1, vcc--power_3v3_a DATA gpio[mode="output"] vin--GPIO18;
    """
    model = mm.model_from_str(demol_str_redis)
    demol2smauto(model, output_dir=OUTPUT_DIR)

    with open(os.path.join(OUTPUT_DIR, "RedisTestSmAutoModel.auto"), "r") as f:
        content = f.read()
    assert "Broker<Redis> RedisBroker" in content
    assert "db: 0" in content
